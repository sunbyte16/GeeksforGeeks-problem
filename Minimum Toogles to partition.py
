class Solution:
    def minToggle(self, arr):
        n = len(arr)

        prefix_ones = [0] * (n + 1)

        for i in range(n):
            prefix_ones[i + 1] = prefix_ones[i] + arr[i]

        suffix_zeros = [0] * (n + 1)

        for i in range(n - 1, -1, -1):
            suffix_zeros[i] = suffix_zeros[i + 1] + (1 if arr[i] == 0 else 0)

        ans = float('inf')

        for i in range(n + 1):
            toggles = prefix_ones[i] + suffix_zeros[i]
            ans = min(ans, toggles)

        return ans